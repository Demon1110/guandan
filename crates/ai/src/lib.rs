//! `gf-ai`：本地 bot（M1）。
//!
//! 纪律（`docs/开发计划.md` §2 模块表、R8）：
//! - **决策输入只有 `view(seat)` 字节、座位号与房间下发的本座位合法集**，不读 `State`、
//!   不看别人手牌（§3.3 约束 3）。合法集由引擎按本座位手牌 + 桌面公开信息推出，不构成泄漏；
//! - 只做确定性整数判断，不接时钟、不用随机（§3.3）；
//! - 决策不保证合法：合法性由房间用 `legal_actions` 复核，不合法即退化（房间记 `BotIllegal`）。
//!
//! 档位（§5.11）：
//! - **AI-L0 / `easy`**：合法集里取牌力最小的一条（托管同款口径），不做取舍；
//! - **AI-L1 / `normal`**：L0 + 牌型取舍——能一把走完就出完、领出先走多张、跟牌只压同张数
//!   的最小代价、上一手是搭档就让牌权；
//! - **AI-L2 / `hard`**：L1 + 记牌（用 `discard` 推断谁还能压）与炸弹时机（按手上的炸弹数
//!   定开炸门槛）。

